// 検索用の文字列正規化。
//
// パル名・技名・アイテム名はカタカナなので、ひらがなで打っても引っかかるように
// 検索語と検索対象の両方をカタカナに寄せてから比較する。
//
// 以前は各ページが同じ関数を個別に持っており(9ページ)、しかも出現マップだけ
// 「カタカナ→ひらがな」と変換方向が逆だった。ページ内で揃っていれば動くものの、
// コピペで混ざると検索が壊れるため、ここに集約して方向を統一する(2026-08)。
function toKana(str){
  return (str || "").replace(/[ぁ-ゖ]/g, ch => String.fromCharCode(ch.charCodeAt(0) + 0x60));
}
